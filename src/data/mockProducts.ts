// Generate more products by duplicating with slight variations
function generateProducts(count: number): Product[] {
  const result: Product[] = [...baseProducts]
  const extras = [
    { brand: 'L\'Oréal', category: 'Chăm sóc da', categorySlug: 'skincare', price: 450_000 },
    { brand: 'MAC', category: 'Trang điểm', categorySlug: 'makeup', price: 780_000 },
    { brand: 'Innisfree', category: 'Chăm sóc da', categorySlug: 'skincare', price: 320_000 },
    { brand: 'The Ordinary', category: 'Chăm sóc da', categorySlug: 'skincare', price: 280_000 },
  ]
  for (let i = baseProducts.length; i < count; i++) {
    const extra = extras[i % extras.length]
    result.push({
      ...baseProducts[i % baseProducts.length],
      id: i + 1,
      slug: `product-${i + 1}`,
      name: `${extra.brand} Sản phẩm ${i + 1}`,
      brand: extra.brand,
      category: extra.category,
      categorySlug: extra.categorySlug,
      price: extra.price,
      originalPrice: undefined,
      discount: undefined,
      sku: `SKU-${i + 1}`,
      isNew: i % 3 === 0,
      isBestSeller: i % 4 === 0,
      isSale: i % 5 === 0,
      createdAt: '2025-03-01T00:00:00Z',
    })
  }
  return result.slice(0, count)
}

